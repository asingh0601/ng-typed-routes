import type { TreeNode } from './tree.js';
import { quote } from './analyzer.js';

export interface EmitOptions {
  /** Path of the source routes file, shown in the header (relative, forward slashes). */
  sourceLabel: string;
  /** Name of the exported constant. Default `routes`. */
  constName?: string;
  /** Module to import `route`/`meta` from. Default `ng-typed-routes`. */
  importFrom?: string;
}

const INDENT = '  ';

/** Prints the named tree as a deterministic, formatted TypeScript module. */
export function emitTree(root: TreeNode, options: EmitOptions): string {
  const constName = options.constName ?? 'routes';
  const importFrom = options.importFrom ?? 'ng-typed-routes';
  const usesMeta = hasMeta(root);
  const body = emitChildren(root, 1);
  const lines: string[] = [
    '/* eslint-disable */',
    '/**',
    ` * Generated by ng-typed-routes from ${options.sourceLabel}.`,
    ' * Do not edit by hand. Run `ng-typed-routes generate` to update it,',
    ' * or `ng-typed-routes check` in CI to make sure it is current.',
    ' */',
    `import { route${usesMeta ? ', meta' : ''} } from ${quote(importFrom)};`,
    '',
    `export const ${constName} = {`,
    ...body,
    '};',
    '',
    `export type ${pascal(constName)}Tree = typeof ${constName};`,
    '',
  ];
  return lines.join('\n');
}

function emitChildren(node: TreeNode, depth: number): string[] {
  const lines: string[] = [];
  const pad = INDENT.repeat(depth);
  for (const [key, child] of node.children) {
    const childLines = emitChildren(child, depth + 1);
    if (child.pattern === undefined) {
      // pure group
      if (childLines.length === 0) continue;
      lines.push(`${pad}${key}: {`, ...childLines, `${pad}},`);
      continue;
    }
    const meta = metaArg(child);
    if (childLines.length === 0 && !meta) {
      lines.push(`${pad}${key}: route(${quote(child.pattern)}),`);
    } else if (childLines.length === 0) {
      lines.push(`${pad}${key}: route(${quote(child.pattern)}, {}, ${meta}),`);
    } else {
      lines.push(`${pad}${key}: route(${quote(child.pattern)}, {`, ...childLines);
      lines.push(meta ? `${pad}}, ${meta}),` : `${pad}}),`);
    }
  }
  return lines;
}

function metaArg(node: TreeNode): string | undefined {
  if (!node.queryType && !node.dataType) return undefined;
  const parts: string[] = [];
  if (node.queryType) parts.push(`query: ${node.queryType}`);
  if (node.dataType) parts.push(`data: ${node.dataType}`);
  const codec = node.queryCodec
    ? `{ ${Object.entries(node.queryCodec)
        .map(([k, v]) => `${k}: ${quote(v)}`)
        .join(', ')} }`
    : '';
  return `meta<{ ${parts.join('; ')} }>(${codec})`;
}

function hasMeta(node: TreeNode): boolean {
  for (const child of node.children.values()) {
    if (child.queryType || child.dataType || hasMeta(child)) return true;
  }
  return false;
}

function pascal(name: string): string {
  return name.charAt(0).toUpperCase() + name.slice(1);
}

/** Normalizes generated code for comparison so formatter differences don't produce false `check` failures. */
export function normalizeForCompare(code: string): string {
  return code
    .replace(/\r\n/g, '\n')
    .replace(/\/\*[\s\S]*?\*\//g, '')
    .replace(/\/\/.*$/gm, '')
    .replace(/"/g, "'")
    .replace(/,(\s*[}\])])/g, '$1')
    .replace(/;/g, '')
    .replace(/\s+/g, '');
}
